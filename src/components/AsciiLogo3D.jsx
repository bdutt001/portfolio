import React, { useEffect, useMemo, useRef } from "react";
import { createAsciiScene } from "../data/asciiSceneEngine";

const CHAR_ASPECT = 0.5;

export default function AsciiLogo3D({
  cols = 140,
  fontSize = 10,
  speed = 20,
  swing = 0,
  axis = "y",
  mode = "color",
  color = "#e6e6e6",
  desk = true,
  outline = true,
  elevation = 15,
  distance = 6.4,
  fov = 34,
  fps = 30,
  paused = false,
  className,
  style,
  ...rest
}) {
  const preRef = useRef(null);
  const renderer = useMemo(
    () => createAsciiScene({ cols, axis, mode, desk, outline, elevation, distance, fov, charAspect: CHAR_ASPECT }),
    [cols, axis, mode, desk, outline, elevation, distance, fov]
  );

  useEffect(() => {
    const pre = preRef.current;
    if (!pre) return undefined;
    const reduced =
      typeof window !== "undefined" && window.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
    const draw = (angle) => {
      const f = renderer.render(angle);
      if (mode === "color") pre.innerHTML = f.html; // markup is generated by the engine only
      else pre.textContent = f.text;
    };
    const rad = Math.PI / 180;
    if (paused || reduced) {
      draw(20 * rad);
      return undefined;
    }
    let raf;
    let lastDraw = -Infinity;
    const start = performance.now();
    const minGap = 1000 / fps;
    const tick = (now) => {
      raf = requestAnimationFrame(tick);
      if (now - lastDraw < minGap) return;
      lastDraw = now;
      const deg = ((now - start) / 1000) * speed; // degrees travelled so far
      draw(swing ? swing * rad * Math.sin(deg * rad) : deg * rad);
    };
    raf = requestAnimationFrame(tick);
    return () => cancelAnimationFrame(raf);
  }, [renderer, mode, speed, swing, paused, fps]);

  return (
    <pre
      ref={preRef}
      role="img"
      aria-label="Rotating 3D ASCII scene: a frog wearing headphones, working at a laptop on a desk"
      className={className}
      style={{
        margin: 0,
        fontFamily: 'ui-monospace, "SF Mono", Menlo, Consolas, "DejaVu Sans Mono", monospace',
        fontSize: typeof fontSize === "number" ? `${fontSize}px` : fontSize,
        lineHeight: 1.2,
        letterSpacing: 0,
        whiteSpace: "pre",
        userSelect: "none",
        color: mode === "mono" ? color : undefined,
        ...style,
      }}
      {...rest}
    />
  );
}
